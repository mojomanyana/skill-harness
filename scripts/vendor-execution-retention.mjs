#!/usr/bin/env node
// Vendor immutable producer contract bytes and its pure validation implementation. No network or installs.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import ts from 'typescript';
const [repo, commit, mode = '--check'] = process.argv.slice(2);
if (!repo || !/^[a-f0-9]{40}$/.test(commit ?? '') || !['--check', '--write'].includes(mode)) throw Error('usage: vendor-execution-retention.mjs <local producer repo> <exact commit> --check|--write');
const git = (...args) => execFileSync('git', ['-C', resolve(repo), ...args], { maxBuffer: 16 * 1024 * 1024 });
if (git('rev-parse', `${commit}^{commit}`).toString().trim() !== commit) throw Error('commit mismatch');
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const prefix = 'packages/pi-daddy/contracts/execution-retention/v2/';
const entries = git('ls-tree', '-r', commit, '--', prefix).toString().trim().split('\n');
const output = new Map(); const sourceHashes = {};
for (const entry of entries) {
  const match = /^100644 blob [a-f0-9]{40}\t(.+)$/.exec(entry); if (!match) throw Error('non-regular contract entry');
  const path = match[1], bytes = git('show', `${commit}:${path}`); sourceHashes[path] = sha(bytes);
  output.set(`contracts/pi-daddy/execution-retention/v2/${path.slice(prefix.length)}`, bytes);
}
const header = `// GENERATED by scripts/vendor-execution-retention.mjs from pi-daddy ${commit}. Do not hand-edit.\n`;
const mappings = {
  'retention-contract.ts': 'retention-v2-contract.ts', 'work-ledger-json.ts': 'retention-v2-json.ts',
  'work-ledger-types.ts': 'retention-v2-work-types.ts', 'native-session.ts': 'retention-v2-native.ts',
  'retention-json.ts': 'retention-v2-native-json.ts', 'execution-retention.ts': 'retention-v2-types.ts',
};
for (const [name, target] of Object.entries(mappings)) {
  const path = `packages/pi-daddy/src/${name}`, bytes = git('show', `${commit}:${path}`); sourceHashes[path] = sha(bytes);
  let text = bytes.toString('utf8');
  if (name === 'execution-retention.ts') {
    const ast = ts.createSourceFile(name, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
    const names = new Set(['RetentionIdentity', 'RetainedContent', 'ExecutionRetentionManifest']);
    const selected = ast.statements.filter(s => ts.isInterfaceDeclaration(s) && names.has(s.name.text));
    if (selected.length !== names.size) throw Error('producer type extraction drift');
    text = 'import type { NativeSessionObservation } from "./native-session.ts";\n' + selected.map(s => s.getText(ast)).join('\n');
  }
  for (const [from, to] of Object.entries(mappings)) text = text.replaceAll(`./${from}`, `./${to.replace(/\.ts$/, '.js')}`);
  if (/from ["']\.\/.+\.ts["']/.test(text)) throw Error('unmapped producer import');
  output.set(`packages/adapters/src/generated/${target}`, Buffer.from(header + text));
}
const license = git('show', `${commit}:LICENSE`); output.set('contracts/pi-daddy/execution-retention/v2/PRODUCER-LICENSE', license);
output.set('packages/adapters/src/generated/retention-v2-pin.ts', Buffer.from(header + `export const RETENTION_V2_COMMIT = ${JSON.stringify(commit)};\nexport const RETENTION_V2_SCHEMA_SHA256 = ${JSON.stringify(sourceHashes[prefix + 'manifest.schema.json'])};\n`));
const generated = Object.fromEntries([...output].map(([path, bytes]) => [path, sha(bytes)]));
output.set('contracts/pi-daddy/execution-retention/v2/PINNED.json', Buffer.from(JSON.stringify({ repository: 'https://github.com/mojomanyana/pi-daddy', commit, tree: git('rev-parse', `${commit}^{tree}`).toString().trim(), contract: 'execution-retention/2.0', source_sha256: sourceHashes, generated_sha256: generated }, null, 2) + '\n'));
function inventory(directory) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const path = `${directory}/${entry.name}`;
    if (entry.isSymbolicLink()) throw Error('symlink in generated contract');
    return entry.isDirectory() ? inventory(path) : [path];
  });
}
const existing = [...inventory('contracts/pi-daddy/execution-retention/v2'), ...inventory('packages/adapters/src/generated').filter(path => /\/retention-v2-/.test(path))];
for (const path of existing) if (!output.has(path)) throw Error(`unexpected contract inventory: ${path}`);
for (const [path, bytes] of output) {
  if (mode === '--write') { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, bytes); }
  else if (!readFileSync(path).equals(bytes)) throw Error(`pinned bytes differ: ${path}`);
}
console.log(`${mode === '--write' ? 'wrote' : 'verified'} ${output.size} pinned files from ${commit}; no provider calls`);
