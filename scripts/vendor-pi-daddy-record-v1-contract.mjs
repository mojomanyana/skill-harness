#!/usr/bin/env node
// Exact pinned producer bytes; never read an uncommitted producer work tree.
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {mkdirSync,readFileSync,writeFileSync,existsSync} from 'node:fs';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=join(dirname(fileURLToPath(import.meta.url)),'..');
const checkout=process.argv[2],check=process.argv.includes('--check');
if(!checkout)throw new Error('usage: vendor-pi-daddy-record-v1-contract.mjs <producer-checkout> [--check]');
const commit='38418793efb785bc582c4a233a18c40364ccd1be',tree='f77fa3b1f81705d640d2ffe4f77dedf0961a32bd',version='0.44.3';
const git=(...args)=>execFileSync('git',['-C',checkout,...args],{encoding:'utf8'});
if(git('rev-parse',commit+'^{tree}').trim()!==tree)throw new Error('Producer tree mismatch');
const show=path=>git('show',commit+':'+path);
if(JSON.parse(show('packages/pi-daddy/package.json')).version!==version)throw new Error('Producer version mismatch');
const source='packages/pi-daddy/contracts/ledger-record/v1',dest=join(root,'contracts/pi-daddy/ledger-record/v1');
const files=['record.schema.json','governance-event.schema.json','README.md','fixtures/ledger-record.jsonl',...['capability-decision','workspace-lease','child-lifecycle','episode-cost-gate','session-config','episode-outcome'].map(x=>'fixtures/'+x+'.json')];
const sha=text=>createHash('sha256').update(text).digest('hex'),artifacts={},writes=[];
for(const file of files){const text=show(source+'/'+file);artifacts[file]={source:source+'/'+file,sha256:sha(text)};writes.push([join(dest,file),text]);}
const readerSource='packages/pi-daddy/src/governance/record.ts';
const reader=show(readerSource);artifacts['record.ts']={source:readerSource,sha256:sha(reader)};writes.push([join(dest,'record.ts'),reader]);
const pinned={producer:'pi-daddy',repository:'mojomanyana/pi-daddy',commit,tree,version,recordVersion:1,ledgerVersion:3,artifacts,note:'Independent current record pin. Historical ledger v2 and bare-v3 pins remain unchanged. Schemas and producer fixtures are byte exact.'};
writes.push([join(dest,'PINNED.json'),JSON.stringify(pinned,null,2)+'\n']);
const runtime='// GENERATED by scripts/vendor-pi-daddy-record-v1-contract.mjs; do not hand-edit.\n'+
'export const PI_DADDY_RECORD_V1_COMMIT = '+JSON.stringify(commit)+';\n'+
'export const PI_DADDY_RECORD_V1_VERSION = '+JSON.stringify(version)+';\n'+
'export const PI_DADDY_RECORD_V1_SCHEMA = '+JSON.stringify(JSON.parse(show(source+'/record.schema.json')),null,2)+' as const;\n'+
'export const PI_DADDY_RECORD_V1_GOVERNANCE_SCHEMA = '+JSON.stringify(JSON.parse(show(source+'/governance-event.schema.json')),null,2)+' as const;\n';
writes.push([join(root,'packages/adapters/src/pi-daddy-record-v1-contract.ts'),runtime]);
for(const [path,text] of writes){if(check){if(!existsSync(path)||readFileSync(path,'utf8')!==text)throw new Error('Pinned bytes differ: '+path);}else{mkdirSync(dirname(path),{recursive:true});writeFileSync(path,text);}}
console.log(check?'Current-record pin verified':'Pinned pi-daddy '+version+' current record contract');
