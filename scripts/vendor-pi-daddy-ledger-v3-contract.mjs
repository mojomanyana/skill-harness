#!/usr/bin/env node
// Vendor or deterministically check the separately versioned pi-daddy ledger-v3 contract.
// Source bytes come from `git show <commit>:<path>`, never the producer working tree.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..");
const DEST = join(REPO, "contracts", "pi-daddy", "ledger", "v3");
const SOURCE_DIR = "packages/pi-daddy/contracts/ledger/v3";
const REFUSAL_SOURCE = "packages/pi-daddy/src/refusals.ts";
const GENERATOR_SOURCE = "packages/pi-daddy/scripts/generate-ledger-v3-contract.ts";
const FIXTURES = ["capability-decision", "workspace-lease", "child-lifecycle", "check-receipt", "workflow-fact"];
const PRODUCERS = {
  "591abb4a358bf8a84455486812b83609e2a47e3f": {
    tree: "c9fe1b324ffbf0d72e7d904972594b3a936e9928",
    version: "0.20.0",
  },
};

const args = process.argv.slice(2);
const check = args.includes("--check");
const positional = args.filter((arg) => arg !== "--check");
if (positional.length !== 2) {
  console.error("usage: node scripts/vendor-pi-daddy-ledger-v3-contract.mjs <pi-daddy-checkout> <commit> [--check]");
  process.exit(2);
}
const [checkout, commit] = positional;
const release = PRODUCERS[commit];
if (!release) {
  console.error(`no authoritative ledger-v3 producer metadata recorded for ${commit}`);
  process.exit(2);
}
const capture = (command, commandArgs) => execFileSync(command, commandArgs, { encoding: "utf8" });
try { execFileSync("git", ["-C", checkout, "cat-file", "-e", `${commit}^{commit}`], { stdio: "ignore" }); }
catch { console.error(`${checkout} does not contain producer commit ${commit}`); process.exit(2); }
const tree = capture("git", ["-C", checkout, "rev-parse", `${commit}^{tree}`]).trim();
if (tree !== release.tree) { console.error(`producer tree ${tree} does not match recorded ${release.tree}`); process.exit(2); }
const show = (source) => capture("git", ["-C", checkout, "show", `${commit}:${source}`]);
const packageVersion = JSON.parse(show("packages/pi-daddy/package.json")).version;
if (packageVersion !== release.version) { console.error(`producer version ${packageVersion} does not match recorded ${release.version}`); process.exit(2); }
const sha256 = (value) => createHash("sha256").update(value).digest("hex");
const files = [
  { source: `${SOURCE_DIR}/ledger-event.schema.json`, dest: "ledger-event.schema.json" },
  { source: `${SOURCE_DIR}/README.md`, dest: "pi-daddy-README.md" },
  { source: REFUSAL_SOURCE, dest: "refusals.ts" },
  ...FIXTURES.map((name) => ({ source: `${SOURCE_DIR}/fixtures/${name}.json`, dest: `fixtures/${name}.json`, generated_by: GENERATOR_SOURCE })),
];
const generated = new Map();
const artifacts = {};
for (const file of files) {
  const text = show(file.source);
  generated.set(join(DEST, file.dest), text);
  artifacts[file.dest] = {
    source: file.source,
    sha256: sha256(text),
    ...(file.generated_by ? { generated_by: file.generated_by } : {}),
  };
}
const schemaText = generated.get(join(DEST, "ledger-event.schema.json"));
const pinned = {
  producer: "pi-daddy",
  repository: "mojomanyana/pi-daddy",
  commit,
  tree,
  version: release.version,
  ledger_version: 3,
  source_schema: `${SOURCE_DIR}/ledger-event.schema.json`,
  source_fixture_generator: GENERATOR_SOURCE,
  source_refusal_enumeration: REFUSAL_SOURCE,
  schema_sha256: sha256(schemaText),
  source_dir: SOURCE_DIR,
  note: "Byte-exact ledgerVersion 3 contract artifacts from the pinned producer. Positive fixtures are emitted by the producer's production builders through generate-ledger-v3-contract.ts; the independent real-builder verifier proves that lineage. This pin is separate from and does not alter the frozen ledger-v2/0.17 pin.",
  artifacts,
};
generated.set(join(DEST, "PINNED.json"), `${JSON.stringify(pinned, null, 2)}\n`);
const runtime = `// GENERATED by scripts/vendor-pi-daddy-ledger-v3-contract.mjs — do not edit by hand.\n// Separate from the frozen ledger-v2 module and legacy 0.17 dispatch.\n\nexport const PI_DADDY_LEDGER_V3_CONTRACT_COMMIT = ${JSON.stringify(commit)};\nexport const PI_DADDY_LEDGER_V3_CONTRACT_TREE = ${JSON.stringify(tree)};\nexport const PI_DADDY_LEDGER_V3_SCHEMA_SHA256 = ${JSON.stringify(sha256(schemaText))};\nexport const PI_DADDY_LEDGER_V3_SCHEMA = ${JSON.stringify(JSON.parse(schemaText), null, 2)} as const;\n`;
generated.set(join(REPO, "packages", "adapters", "src", "pi-daddy-ledger-v3.ts"), runtime);
let mismatches = 0;
for (const [target, text] of generated) {
  if (check) {
    if (!existsSync(target) || readFileSync(target, "utf8") !== text) {
      console.error(`out of date: ${target.slice(REPO.length + 1)}`);
      mismatches += 1;
    }
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, text);
  }
}
if (check) {
  if (mismatches) process.exit(1);
  console.log(`pi-daddy ledger-v3 pin is deterministic and current at ${commit}`);
} else {
  console.log(`vendored ${files.length} ledger-v3 artifact(s) from ${commit}`);
  for (const [name, artifact] of Object.entries(artifacts)) console.log(`  ${artifact.sha256}  ${name}`);
}
